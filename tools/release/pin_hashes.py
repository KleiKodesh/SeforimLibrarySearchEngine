"""Writes dart/seforim_search/lib/src/hook/asset_hashes.g.dart from a
release's SHA256SUMS (lines "<sha256>  <file>").

    python -I -X utf8 tools/release/pin_hashes.py <tag> <SHA256SUMS> [out.dart]

Run by the release workflow; locally after `gh release download <tag> -p SHA256SUMS`.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from targets import TARGETS, release_file  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DEFAULT_OUT = os.path.join(ROOT, "dart", "seforim_search", "lib", "src", "hook", "asset_hashes.g.dart")


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    tag, sums = sys.argv[1], sys.argv[2]
    out = sys.argv[3] if len(sys.argv) > 3 else DEFAULT_OUT
    if not re.fullmatch(r"v\d+\.\d+\.\d+([-+][0-9A-Za-z.\-+]*)?", tag):
        sys.exit(f"bad tag {tag!r}: expected v<semver>")
    known = {release_file(n) for n, *_ in TARGETS}
    hashes = {}
    with open(sums, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            h, name = line.split(None, 1)
            name = name.lstrip("*")
            if name in known:
                if not re.fullmatch(r"[0-9a-f]{64}", h):
                    sys.exit(f"bad sha256 for {name}: {h}")
                hashes[name] = h
    missing = [release_file(n) for n, _, _, req in TARGETS if req and release_file(n) not in hashes]
    if missing:
        sys.exit("SHA256SUMS lacks required targets: " + ", ".join(missing))
    body = "".join(f"  '{k}': '{hashes[k]}',\n" for k in sorted(hashes))
    text = (
        "// SHA-256 of the prebuilt native libraries in the GitHub release `releaseTag`.\n"
        "// GENERATED by tools/release/pin_hashes.py from the release's SHA256SUMS; do not edit.\n"
        "// The build hook downloads a prebuilt library only when `releaseTag` is\n"
        "// `v<package version>` and the target is listed here.\n\n"
        "// ignore: unnecessary_nullable_for_final_variable_declarations\n"
        f"const String? releaseTag = '{tag}';\n\n"
        "const Map<String, String> assetSha256 = {\n" + body + "};\n"
    )
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"pinned {len(hashes)} libraries of {tag} -> {out}")


if __name__ == "__main__":
    main()
