"""Generates THIRD-PARTY-NOTICES.md: every Rust crate linked into the native
library (engine-ffi's normal dependency graph, all release targets), with its
version, license expression and repository, from `cargo metadata` (no extra
tool needed).

    python -I -X utf8 tools/release/third_party.py           # rewrite the file
    python -I -X utf8 tools/release/third_party.py --check   # CI: fail if stale
"""
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "THIRD-PARTY-NOTICES.md")


def generate():
    meta = json.loads(subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked"],
        cwd=ROOT, check=True, capture_output=True, text=True, encoding="utf-8").stdout)
    pkgs = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    workspace = set(meta["workspace_members"])
    root = next(i for i in workspace if pkgs[i]["name"] == "engine-ffi")
    seen, stack = set(), [root]
    while stack:
        cur = stack.pop()
        if cur in seen:
            continue
        seen.add(cur)
        for dep in nodes[cur]["deps"]:
            if any(k["kind"] in (None, "build") for k in dep["dep_kinds"]):
                stack.append(dep["pkg"])
    rows = []
    for pid in seen:
        p = pkgs[pid]
        if pid in workspace:
            continue
        rows.append((p["name"], p["version"], p.get("license") or ("see " + p["license_file"] if p.get("license_file") else "UNKNOWN"),
                     p.get("repository") or ""))
    rows.sort()
    by_license = {}
    for r in rows:
        by_license[r[2]] = by_license.get(r[2], 0) + 1
    lines = [
        "# Third-party notices",
        "",
        "The native library `seforim_search_native` (engine-ffi) links the Rust crates below.",
        "GENERATED by `tools/release/third_party.py` from `cargo metadata`; do not edit.",
        "Each crate's license text is in its source package (crates.io / its repository).",
        "The modified tantivy copy (`tantivy/`, MIT) is part of this repository's workspace.",
        "",
        "## Licenses",
        "",
        "| License | Crates |",
        "| --- | ---: |",
    ]
    lines += [f"| {lic} | {n} |" for lic, n in sorted(by_license.items())]
    lines += ["", "## Crates", "", "| Crate | Version | License | Repository |", "| --- | --- | --- | --- |"]
    lines += [f"| {n} | {v} | {lic} | {repo} |" for n, v, lic, repo in rows]
    return "\n".join(lines) + "\n"


def main():
    text = generate()
    if "--check" in sys.argv:
        try:
            with open(OUT, encoding="utf-8") as f:
                old = f.read()
        except FileNotFoundError:
            old = ""
        if old != text:
            sys.exit("THIRD-PARTY-NOTICES.md is stale: run python -I -X utf8 tools/release/third_party.py")
        print("THIRD-PARTY-NOTICES.md: up to date")
        return
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
