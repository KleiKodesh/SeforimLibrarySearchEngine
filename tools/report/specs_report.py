def splice(path, block):
    if not os.path.exists(path):
        return
    s = open(path, encoding="utf-8").read()
    b, e = "<!-- SPECS:BEGIN (generated by tools/report/specs_report.py) -->", "<!-- SPECS:END -->"
    if b in s and e in s:
        s = s[:s.index(b) + len(b)] + "\n" + block + "\n" + s[s.index(e):]
        open(path, "w", encoding="utf-8", newline="\n").write(s)
        print("updated", path)
    else:
        print("no SPECS markers in", path)


splice(os.path.join(ROOT, "README.md"), readme_block)
splice(os.path.join(ROOT, "CLAUDE.md"), claude_block)
