def t(ms):
    """ms below one second, minutes otherwise (never seconds)."""
    if ms is None:
        return "n/a"
    return f"{ms:,.0f} ms" if ms < 1000 else f"{ms / 60000:.2f} min"


def load(set_, pattern):
    p = os.path.join(SP, pattern.format(set=set_), "search-report.json")
    if not os.path.exists(p):
        return None
    try:
        d = json.load(open(p, encoding="utf-8"))
    except Exception:
        return None
    rows = [r for r in d.get("rows", []) if r.get("exit", 1) == 0 and r.get("total_ms") is not None]
    return {"rows": {r["n"]: r for r in rows}, "all": d.get("rows", [])}


def build(log):
    p = os.path.join(SP, "logs", log)
    if not os.path.exists(p):
        return None
    s = open(p, encoding="utf-8", errors="replace").read()
    st = {m.group(1).split("(")[0].strip(): float(m.group(2)) * 1000
          for m in re.finditer(r"stage: ([^:]+): ([\d.]+)s", s)}
    size = re.search(r"index size: ([\d.]+) MB", s)
    files = re.findall(r"^\s+(\.\w+)\s+([\d.]+) MB", s, re.M)
    return {"stages": st, "total": sum(st.values()), "size": float(size.group(1)) if size else None,
            "files": [(f, float(m)) for f, m in files if float(m) > 0]}


def bar_chart(title, ylabel, labels, series, unit_div):
    out = ["```mermaid", "xychart-beta", f'    title "{title}"',
           "    x-axis [" + ", ".join(f'"{l}"' for l in labels) + "]", f'    y-axis "{ylabel}"']
    for _, vals in series:
        out.append("    bar [" + ", ".join(f"{(v or 0) / unit_div:.2f}" for v in vals) + "]")
    out.append("```")
    legend = " / ".join(f"bar {i + 1} = {name}" for i, (name, _) in enumerate(series))
    return "\n".join(out) + f"\n\n_Bars in order: {legend}._\n"


