# ---- generated summaries in README.md and CLAUDE.md (between the SPECS markers) ----
def speed_lines():
    out = []
    for set_, title in SETS:
        cells = []
        for name, pat in ENGINES:
            d = load(set_, pat)
            if d and d["rows"]:
                rows = list(d["rows"].values())
                first = [r["first_ms"] for r in rows if r.get("first_ms") is not None]
                cells.append(f"{name}: median {t(statistics.median([r['total_ms'] for r in rows]))}"
                             + (f", first batch {t(statistics.median(first))}" if first else ""))
        out.append(f"| {title} | " + "; ".join(cells) + " |")
    return out


def build_lines():
    out = []
    for name, b in bl:
        if b:
            out.append(f"| {name} | {t(b['total'])} | {b['size']:,.1f} MB |")
    out.append("| FtsLib (fts8) | 16.2 min | 746.0 MB |")
    out.append("| Otzaria v5.0.0 | 8.1 min | 1,914 MB |")
    return out


