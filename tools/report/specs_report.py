"""Writes FTS-SPECS-AND-COMPARISONS.md at the repo root from the latest build logs
and search_report.py JSON runs. Rerun it whenever new runs land.

    python -I -X utf8 tools/report/specs_report.py <scratchpad>
"""
import json, os, re, statistics, sys, datetime

SP = sys.argv[1]
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "FTS-SPECS-AND-COMPARISONS.md")

ENGINES = [  # (label, run dir prefix)
    ("ours, positions", "r8-sb-{set}-pos"),
    ("ours, no positions", "r8-sb-{set}-nopos"),
    ("FtsLib", "r8-sb-{set}-fts"),
    ("Otzaria", "sb-{set}-otz"),
]
SETS = [("large", "queries-large.txt (61)"), ("words", "queries-words.txt (14)"), ("rules", "queries-rules.txt (21)")]
BUILDS = [("ours, positions", "r8-build-pos.log"), ("ours, no positions", "r8-build-nopos.log"),
          ("ours, positions + keep marks", "r8-build-marks.log")]


def t(ms):
    """ms below one second, minutes otherwise (never seconds)."""
    if ms is None:
        return "n/a"
    return f"{ms:,.0f} ms" if ms < 1000 else f"{ms / 60000:.2f} min"


def load(set_, pattern):
    p = os.path.join(SP, pattern.format(set=set_), "search-report.json")
    if not os.path.exists(p):
        return None
    try:
        d = json.load(open(p, encoding="utf-8"))
    except Exception:
        return None
    rows = [r for r in d.get("rows", []) if r.get("exit", 1) == 0 and r.get("total_ms") is not None]
    return {"rows": {r["n"]: r for r in rows}, "all": d.get("rows", [])}


def build(log):
    p = os.path.join(SP, "logs", log)
    if not os.path.exists(p):
        return None
    s = open(p, encoding="utf-8", errors="replace").read()
    st = {m.group(1).split("(")[0].strip(): float(m.group(2)) * 1000
          for m in re.finditer(r"stage: ([^:]+): ([\d.]+)s", s)}
    size = re.search(r"index size: ([\d.]+) MB", s)
    files = re.findall(r"^\s+(\.\w+)\s+([\d.]+) MB", s, re.M)
    return {"stages": st, "total": sum(st.values()), "size": float(size.group(1)) if size else None,
            "files": [(f, float(m)) for f, m in files if float(m) > 0]}


def bar_chart(title, ylabel, labels, series, unit_div):
    out = ["```mermaid", "xychart-beta", f'    title "{title}"',
           "    x-axis [" + ", ".join(f'"{l}"' for l in labels) + "]", f'    y-axis "{ylabel}"']
    for _, vals in series:
        out.append("    bar [" + ", ".join(f"{(v or 0) / unit_div:.2f}" for v in vals) + "]")
    out.append("```")
    legend = " / ".join(f"bar {i + 1} = {name}" for i, (name, _) in enumerate(series))
    return "\n".join(out) + f"\n\n_Bars in order: {legend}._\n"


md = []
now = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
md.append("# FTS specs and comparisons\n")
md.append(f"_Generated by `tools/report/specs_report.py` on {now}. Kept up to date as the engine changes "
          "(see CLAUDE.md). Units: ms below one second, minutes otherwise._\n")

md.append("""## Engines compared

| Engine | What it is |
|---|---|
| ours, positions | this repo: modified tantivy + hebrew-fts walks, index with positions (span queries) |
| ours, no positions | same engine, index without positions; distance/order checked on the text by the locator |
| FtsLib | KitveiHakodesh FtsLib (SQLite FTS5, `detail=none`, index fts8) |
| Otzaria | otzaria_search_engine v5.0.0 (tantivy), driven by the scratchpad driver |

## Feature specs (ours)

| Feature | Status |
|---|---|
| FtsLib query syntax (`* ? % ~N \\|`), results identical to FtsLib | done, parity below |
| Every option one FST walk per word, shortest first, cap 2000 per segment, matched terms returned | done |
| Otzaria word options (grammar/advanced/Aramaic prefixes+suffixes, ktiv, part of word, typo modes, quotes) | done |
| Ketiv rule sets: Otzaria's or FtsLib's KetivExpander (`ktiv_rules`) | done |
| One search options object, per-word options (negative words too), alternatives, acronyms | done |
| Otzaria proximity (per-pair gaps, any order), word match (all/any/most/at least N) | done |
| Otzaria tokenizer rules (one-letter words, digits, joiners, geresh, paired readings, 128-byte limit) in both engines | done |
| Vocalized matching (nikud / te'amim) as a walk on a keep-marks index | done |
| Exact totals + per-book counts, cancellation, pull streaming | done |
| User regex `/.../` (word, sequence, line kinds) | done |
| Relevance / generation order (option; catalog default) + notice when positions are needed | done |
| Truncated flag when a cap is hit | done |
| Cross-line phrases (one break, any search type) and same-section scope | built; tested by unit tests |
""")

md.append("## Index builds (full DB, 7,080,797 lines)\n")
bl = [(name, build(log)) for name, log in BUILDS]
md.append("| Build | Indexing | Merge | FM sidecar | Total | Size |\n|---|---|---|---|---|---|")
for name, b in bl:
    if not b:
        md.append(f"| {name} | n/a | n/a | n/a | n/a | n/a |")
        continue
    st = b["stages"]
    g = lambda k: next((v for kk, v in st.items() if kk.startswith(k)), None)
    md.append(f"| {name} | {t(g('indexing'))} | {t(g('merge'))} | {t(g('FM'))} | {t(b['total'])} | {b['size']:,.1f} MB |")
md.append("\nReference builds measured earlier: FtsLib fts8 16.2 min / 746.0 MB; Otzaria v5.0.0 8.1 min / 1,914 MB "
          "(not merged to one segment).\n")
for name, b in bl:
    if b and b["files"]:
        md.append(f"**{name}, per file:** " + ", ".join(f"`{f}` {m:,.1f} MB" for f, m in b["files"]) + "\n")
ok = [(n, b) for n, b in bl if b]
if ok:
    md.append(bar_chart("Index build time (minutes)", "minutes", [n for n, _ in ok],
                        [("total", [b["total"] for _, b in ok])], 60000))
    md.append(bar_chart("Index size (MB)", "MB", [n for n, _ in ok], [("size", [b["size"] for _, b in ok])], 1))

md.append("""## Parity with FtsLib (identical lines, first 20,000 hits, both index flavours)

| Set | Positions | No positions |
|---|---|---|
| queries-diff10 | 10/10 | 10/10 |
| queries-large | 61/61 | 61/61 |
| queries-words | 14/14 | 14/14 |
| queries-rules | 21/21 | 21/21 |
| queries-ketiv (ketiv on) | 12/12 | 12/12 |
""")

md.append("## Search speed (every hit read, median of 3 runs after one warm-up)\n")
md.append("Stages per query: walks + collect (engine), host (text fetch + locate + widening), first batch, total. "
          "Otzaria runs only the queries it has an equivalent for (no `*`, `?`, `%`, `|`, phrase); its large-set "
          "timings come from an earlier run on a busier machine, so treat them as indicative.\n")
for set_, title in SETS:
    data = [(name, load(set_, pat)) for name, pat in ENGINES]
    md.append(f"### {title}\n")
    md.append("| Engine | Queries run | Total (sum) | Median per query | First batch median | Slowest query |\n|---|---|---|---|---|---|")
    have = []
    for name, d in data:
        if not d or not d["rows"]:
            md.append(f"| {name} | pending | | | | |")
            continue
        rows = list(d["rows"].values())
        tot = [r["total_ms"] for r in rows]
        first = [r["first_ms"] for r in rows if r.get("first_ms") is not None]
        slow = max(rows, key=lambda r: r["total_ms"])
        md.append(f"| {name} | {len(rows)} | {t(sum(tot))} | {t(statistics.median(tot))} | "
                  f"{t(statistics.median(first)) if first else 'n/a'} | q{slow['n'] + 1}: {t(slow['total_ms'])} |")
        have.append((name, d))
    md.append("")
    if not have:
        continue
    # common queries for fair totals
    common = sorted(set.intersection(*[set(d["rows"]) for _, d in have]))
    if len(have) > 1 and common:
        md.append(f"Over the {len(common)} queries every engine ran:\n")
        md.append(bar_chart(f"{set_}: total time over common queries (minutes)", "minutes", [n for n, _ in have],
                            [("total", [sum(d['rows'][q]['total_ms'] for q in common) for _, d in have])], 60000))
        md.append(bar_chart(f"{set_}: median first batch (ms)", "ms", [n for n, _ in have],
                            [("first", [statistics.median([d['rows'][q].get('first_ms') or 0 for q in common]) for _, d in have])], 1))
    qs = sorted(set.union(*[set(d["rows"]) for _, d in have]))
    md.append(bar_chart(f"{set_}: total per query (minutes)", "minutes", [f"q{q + 1}" for q in qs],
                        [(n, [d["rows"].get(q, {}).get("total_ms") for q in qs]) for n, d in have], 60000))
    md.append("<details><summary>Per query, each stage</summary>\n")
    md.append("| q | Query | Engine | Hits | Walks + collect | Host | First batch | Total |\n|---|---|---|---|---|---|---|---|")
    for q in qs:
        for n, d in have:
            r = d["rows"].get(q)
            if not r:
                continue
            md.append(f"| q{q + 1} | `{r.get('query', '')}` {r.get('dist', '') if r.get('dist') not in (None, '-') else ''} | {n} | "
                      f"{int(r.get('hits') or 0):,} | {t(r.get('walks_collect_ms'))} | {t(r.get('host_ms'))} | "
                      f"{t(r.get('first_ms'))} | {t(r.get('total_ms'))} |")
    md.append("\n</details>\n")

md.append("## Hit-count comparison with Otzaria\n")
hc_path = os.path.join(SP, "otz-hitcount.json")
if not os.path.exists(hc_path):
    md.append("Pending: filled in from the comparison run (same queries, equivalent options; differences analysed: whose bug).\n")
else:
    hc = json.load(open(hc_path, encoding="utf-8"))
    md.append(hc.get("method", "") + "\n")
    classes = {}
    for rows in hc["sets"].values():
        for r in rows:
            classes[r["class"]] = classes.get(r["class"], 0) + 1
    md.append("| Class | Queries |\n|---|---|")
    for c, k in sorted(classes.items(), key=lambda x: -x[1]):
        md.append(f"| {c} | {k} |")
    md.append("")
    for set_, title in SETS:
        rows = hc["sets"].get(set_)
        if not rows:
            continue
        md.append(f"### {title}\n")
        md.append("| q | Query | Otzaria mode | Otzaria hits | Ours hits | Diff | Class | Reason |\n|---|---|---|---|---|---|---|---|")
        for r in rows:
            d = r["ours"] - r["otz"]
            md.append(f"| q{r['n'] + 1} | `{r['query']}` {r.get('dist') or ''} | {r['mode']} | {r['otz']:,} | {r['ours']:,} | "
                      f"{d:+,} | {r['class']} | {r['reason']} |")
        md.append("")
    if hc.get("notes"):
        md.append("**Causes, with evidence:**\n")
        md.extend(f"- {x}" for x in hc["notes"])
        md.append("")
open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(md))
print("wrote", OUT)
