// Usage: rustc -O gen.rs && ./gen "$(rustc --version)" > .../FtsLib/Tokenization/UnicodeTables.cs
// Generates FtsLib's UnicodeTables.cs from Rust's char::is_alphanumeric and
// char::to_lowercase (the toolchain the engine is built with), so FtsLib's
// word rule equals the engine's.
use std::fmt::Write;

fn main() {
    let mut ranges: Vec<(u32, u32)> = Vec::new();
    let mut lower: Vec<(u32, String)> = Vec::new();
    for cp in 0x80u32..=0x10FFFF {
        let Some(c) = char::from_u32(cp) else { continue };
        if c.is_alphanumeric() {
            match ranges.last_mut() {
                Some(r) if r.1 + 1 == cp => r.1 = cp,
                _ => ranges.push((cp, cp)),
            }
        }
        let l: String = c.to_lowercase().collect();
        if l.chars().count() != 1 || l.chars().next() != Some(c) {
            lower.push((cp, l));
        }
    }
    let mut out = String::new();
    let rustc = std::env::args().nth(1).unwrap_or_default();
    writeln!(out, "// <auto-generated>").unwrap();
    writeln!(out, "// Generated from Rust's char::is_alphanumeric and char::to_lowercase ({rustc}),").unwrap();
    writeln!(out, "// the toolchain the seforim engine is built with, so FtsLib's word rule (Otzaria's)").unwrap();
    writeln!(out, "// matches the engine's char for char. Regenerate when the toolchain's Unicode").unwrap();
    writeln!(out, "// version changes. Do not edit.").unwrap();
    writeln!(out, "// </auto-generated>").unwrap();
    writeln!(out, "namespace FtsLib.Tokenization").unwrap();
    writeln!(out, "{{").unwrap();
    writeln!(out, "    internal static class UnicodeTables").unwrap();
    writeln!(out, "    {{").unwrap();
    writeln!(out, "        /// <summary>Non-ASCII alphanumeric code points (Rust <c>is_alphanumeric</c>) as inclusive [start, end] pairs, sorted.</summary>").unwrap();
    write!(out, "        internal static readonly int[] AlphanumericRanges =\n        {{").unwrap();
    for (i, (a, b)) in ranges.iter().enumerate() {
        if i % 8 == 0 {
            write!(out, "\n            ").unwrap();
        }
        write!(out, "0x{a:X}, 0x{b:X}, ").unwrap();
    }
    writeln!(out, "\n        }};").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "        /// <summary>Non-ASCII code points whose Rust <c>to_lowercase</c> differs from themselves, sorted.</summary>").unwrap();
    write!(out, "        internal static readonly int[] LowercaseFrom =\n        {{").unwrap();
    for (i, (a, _)) in lower.iter().enumerate() {
        if i % 12 == 0 {
            write!(out, "\n            ").unwrap();
        }
        write!(out, "0x{a:X}, ").unwrap();
    }
    writeln!(out, "\n        }};").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "        /// <summary>The lowercase of each <see cref=\"LowercaseFrom\"/> entry.</summary>").unwrap();
    write!(out, "        internal static readonly string[] LowercaseTo =\n        {{").unwrap();
    for (i, (_, l)) in lower.iter().enumerate() {
        if i % 8 == 0 {
            write!(out, "\n            ").unwrap();
        }
        let esc: String = l.encode_utf16().map(|u| format!("\\u{u:04X}")).collect();
        write!(out, "\"{esc}\", ").unwrap();
    }
    writeln!(out, "\n        }};").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "}}").unwrap();
    print!("{out}");
    eprintln!("ranges={} lower={}", ranges.len(), lower.len());
}
